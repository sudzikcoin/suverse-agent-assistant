/**
 * Regenerates the SDK from the door's live tool list: tools.generated.mjs (names and camelCase method names) and
 * index.d.ts (one typed method per tool; inputs from each tool's inputSchema; get_card / get_business typed with the
 * public card schema; other answers are plain JSON objects). Run: node scripts/generate.mjs [url]
 */
import { Client } from '@modelcontextprotocol/sdk/client/index.js'
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js'
import { readFileSync, writeFileSync } from 'node:fs'

const url = process.argv[2] || 'https://versum.suverse.io/mcp'
const root = new URL('..', import.meta.url)
const c = new Client({ name: 'versum-mcp-generate', version: '1' })
await c.connect(new StreamableHTTPClientTransport(new URL(url)))
const { tools } = await c.listTools()
await c.close()

const camel = (s) => s.replace(/_([a-z])/g, (_, x) => x.toUpperCase())
const pascal = (s) => camel(s).replace(/^./, (x) => x.toUpperCase())
const prop = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k))
const doc = (d, ind) => (d ? `${ind}/** ${String(d).replace(/\*\//g, '* /').replace(/\s+/g, ' ').trim()} */\n` : '')

function ts(s, ind = '') {
  if (!s || typeof s !== 'object') return 'unknown'
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ')
  if (s.const !== undefined) return JSON.stringify(s.const)
  if (s.anyOf || s.oneOf) return [...new Set((s.anyOf || s.oneOf).map((x) => ts(x, ind)))].join(' | ')
  const t = Array.isArray(s.type) ? s.type : [s.type]
  const parts = t.map((one) => {
    switch (one) {
      case 'string': return 'string'
      case 'number': case 'integer': return 'number'
      case 'boolean': return 'boolean'
      case 'null': return 'null'
      case 'array': return `Array<${ts(s.items, ind)}>`
      case 'object': {
        const props = s.properties || {}
        const req = new Set(s.required || [])
        const keys = Object.keys(props)
        if (!keys.length) return 'Record<string, unknown>'
        const inner = ind + '  '
        return `{\n${keys.map((k) => `${doc(props[k].description, inner)}${inner}${prop(k)}${req.has(k) ? '' : '?'}: ${ts(props[k], inner)}`).join('\n')}\n${ind}}`
      }
      default: return 'unknown'
    }
  })
  return [...new Set(parts)].join(' | ')
}

const card = JSON.parse(readFileSync(new URL('card.schema.json', root), 'utf8'))
const CARD_TOOLS = new Set(['get_card', 'get_business'])
let dts = `// Generated by scripts/generate.mjs from ${url} on ${new Date().toISOString().slice(0, 10)} — do not edit.\n\n`
dts += `/** A business card, as get_card returns it (schema/card.schema.json in sudzikcoin/versum-agent-assistant). */\nexport type Card = ${ts(card)}\n\n`
for (const t of tools) dts += `${doc(t.title, '')}export type ${pascal(t.name)}Input = ${ts(t.inputSchema)}\n\n`
dts += `export interface VersumOptions {\n  /** the MCP door (default https://versum.suverse.io/mcp) */\n  url?: string\n}\n\n`
dts += `/** A typed client of the Versum MCP door. Every method calls the tool of the same name and returns its JSON answer. */\nexport declare class Versum {\n  constructor(options?: VersumOptions)\n  /** connect explicitly (methods connect on first use) */\n  connect(): Promise<this>\n  close(): Promise<void>\n  /** call any tool by its MCP name */\n  call(name: string, args?: Record<string, unknown>): Promise<Record<string, unknown>>\n`
for (const t of tools) dts += `${doc(t.title, '  ')}  ${camel(t.name)}(args${Object.keys(t.inputSchema?.required || []).length ? '' : '?'}: ${pascal(t.name)}Input): Promise<${CARD_TOOLS.has(t.name) ? 'Card' : 'Record<string, unknown>'}>\n`
dts += `}\n\n/** The open reader's card (reader/README.md in sudzikcoin/versum-agent-assistant). */\nexport type ReaderCard = {\n  reader: { name: string; version: string }\n  url: string\n  final_url: string | null\n  read_at: string\n  platform: { name: string; confidence: number | null } | null\n  business: { name: string | null; phone: string | null; email: string | null; hours: string[] | null }\n  offerings: Array<{ title: string; price: number | null; price_max: number | null; currency: string | null; kind: 'product' | 'menu_item' | 'service'; url: string | null; section: string | null; duration_min: number | null }>\n  doors: Array<{ action: 'order' | 'reserve' | 'book' | 'request_quote' | 'contact' | 'call' | 'email'; method: string | null; url: string; provider: string | null }>\n  delivery: { lead_time: string | null; policy_url: string | null } | null\n  evidence: Array<{ field: string; quote: string; url: string | null }>\n  notes: string[]\n  model: { used: boolean; model: string | null; cost_usd: number }\n}\n\nexport interface ReadOptions {\n  /** a model call with your own ANTHROPIC_API_KEY when nothing structured was found (default true) */\n  model?: boolean\n  /** the free shared cache (default true; VERSUM_SHARE=0 also turns it off) */\n  share?: boolean\n  /** read even when the shared cache has a fresh card */\n  fresh?: boolean\n  /** the cache's address (default https://versum.suverse.io) */\n  base?: string\n}\n\n/** Read one business website on this machine with Versum's open reader. */\nexport declare function read(url: string, options?: ReadOptions): Promise<ReaderCard>\n\nexport declare const TOOLS: ReadonlyArray<{ name: string; method: string }>\n`
writeFileSync(new URL('index.d.ts', root), dts)
writeFileSync(new URL('tools.generated.mjs', root), `// Generated by scripts/generate.mjs from ${url} — do not edit.\nexport const TOOLS = ${JSON.stringify(tools.map((t) => ({ name: t.name, method: camel(t.name) })), null, 2)}\n`)
console.log(`${tools.length} tools → index.d.ts, tools.generated.mjs`)
